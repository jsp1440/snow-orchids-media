// Smoke-test the interactive preview: launch, play, pause, scrub, restart, scene jump.
import { createRequire } from 'node:module';
import { startServer } from './serve.mjs';
const { chromium } = createRequire(import.meta.url)('playwright');
const shot = process.argv[2];
const server = await startServer(8095);
const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 820 } });
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
const ok = (name, cond) => { console.log(`${cond ? 'PASS' : 'FAIL'}  ${name}`); if (!cond) process.exitCode = 1; };
await page.goto('http://localhost:8095/animation/');
await page.waitForFunction(() => document.body.classList.contains('ready'), null, { timeout: 120000 });
ok('app launches (ready)', true);
const time = () => page.$eval('#scrub', (e) => parseFloat(e.value));
await page.click('#play');
await page.waitForTimeout(2500);
const t1 = await time();
ok(`plays (t advanced to ${t1.toFixed(2)})`, t1 > 0.3);
ok('audio playing', await page.$eval('#song', (a) => !a.paused && a.src.includes('song-1')));
await page.click('#play');
const tp = await time(); await page.waitForTimeout(1200); const tp2 = await time();
ok(`pause holds time (${tp.toFixed(2)} -> ${tp2.toFixed(2)})`, Math.abs(tp2 - tp) < 0.05);
await page.$eval('#scrub', (e) => { e.value = 33.3; e.dispatchEvent(new Event('input')); });
await page.waitForFunction(() => document.querySelector('#time').textContent.startsWith('0:33.3'), null, { timeout: 30000 });
ok(`scrub to 33.3 (${(await time()).toFixed(2)}), label "${await page.textContent('#time')}"`, Math.abs((await time()) - 33.3) < 0.05);
ok('scene chip 4 highlighted', await page.$eval('[data-jump="30.7"]', (e) => e.classList.contains('on')));
await page.click('[data-jump="50.7"]'); await page.waitForTimeout(800);
ok('scene jump to 50.7', Math.abs((await time()) - 50.7) < 0.05);
if (shot) await page.screenshot({ path: shot });
await page.click('#restart'); await page.waitForTimeout(1500);
const tr = await time();
ok(`restart plays from 0 (t=${tr.toFixed(2)})`, tr < 1.6 && tr > 0);
await page.$eval('#scrub', (e) => { e.value = 59.7; e.dispatchEvent(new Event('input')); });
await page.waitForFunction(() => document.querySelector('#play').textContent.includes('Play'), null, { timeout: 60000 });
ok(`stops at end (t=${(await time()).toFixed(2)})`, Math.abs((await time()) - 60) < 0.01 && (await page.textContent('#play')).includes('Play'));
ok(`no console errors${errors.length ? ': ' + errors.join(' | ') : ''}`, errors.length === 0);
await browser.close(); server.close();
